/// Перевод для Ренат мода; без него строка возвращается как есть.
pub fn mog(value: SharedString) -> SharedString {
    if !on() {
        return value;
    }
    if let Some((_, to)) = PHRASES.iter().find(|(from, _)| *from == value.as_ref()) {
        return (*to).into();
    }
    let mut out = value.to_string();
    for (from, to) in WORDS {
        if out.contains(from) {
            out = out.replace(from, to);
        }
    }
    out.into()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn phrases_and_words() {
        ON.store(true, Ordering::Relaxed);
        assert_eq!(mog("Связь".into()).as_ref(), "Джоулайн");
        assert_eq!(
            mog("Ошибка: порт занят".into()).as_ref(),
            "Кортизол: порт заморган"
        );
        ON.store(false, Ordering::Relaxed);
        assert_eq!(mog("Связь".into()).as_ref(), "Связь");
    }
}
